#!/usr/bin/env python3
"""
05_visualize_results.py
────────────────────────
GROUP COMPARISON VISUALIZATION ONLY

DeepPrep already generates comprehensive single-subject QC reports:
  outputs/deepprep/QC/sub-XXX_ses-YY.html

This script generates GROUP-LEVEL statistical comparison figures only:
  - Effect size forest plot (Cohen's d)
  - Group mean comparison bar chart
  - Summary table

Outputs → data/processed/figures/
"""
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches

warnings.filterwarnings("ignore")

# ── Paths ─────────────────────────────────────────────────────────────────────
PROJ_DIR = Path(__file__).resolve().parent.parent
ANA_DIR = PROJ_DIR / "outputs" / "analysis" / "structural"
FIG_DIR = PROJ_DIR / "outputs" / "figures"
FIG_DIR.mkdir(parents=True, exist_ok=True)

# ── Find the most recent group comparison file ────────────────────────────────
comp_files = sorted(ANA_DIR.glob("group_comparison_ses-*.csv"))
if not comp_files:
    print("❌ No group comparison results found.")
    print("   Run: python3 code/analysis/04_structural_analysis.py")
    raise SystemExit(1)

STRUCT_CSV = comp_files[-1]   # most recent
SESSION = STRUCT_CSV.stem.split("ses-")[-1]
print(f"[viz] Using results: {STRUCT_CSV.name}")
print(f"[viz] Session: ses-{SESSION}")

res_df = pd.read_csv(STRUCT_CSV)
COLORS = {"heavy": "#C0392B", "control": "#2980B9"}

# ── 1. Effect size forest plot ────────────────────────────────────────────────
print("[viz] Generating effect size forest plot...")
fplot_df = res_df.sort_values("cohens_d", ascending=True).tail(20)

fig, ax = plt.subplots(figsize=(8, 9))
colors_bar = [COLORS["heavy"] if d > 0 else COLORS["control"]
              for d in fplot_df["cohens_d"]]
y = np.arange(len(fplot_df))

ax.barh(y, fplot_df["cohens_d"], color=colors_bar, alpha=0.7)
ax.axvline(0, color="black", linewidth=0.8)
ax.set_yticks(y)
ax.set_yticklabels(
    fplot_df["roi"].str.replace(r"(Left-|Right-|lh_|rh_)", "", regex=True),
    fontsize=8
)
ax.set_xlabel("Cohen's d  (positive = larger in heavy users)", fontsize=10)
ax.set_title(f"Structural Group Differences — ses-{SESSION}\nTop 20 ROIs by Effect Size", fontsize=12)

heavy_p = mpatches.Patch(color=COLORS["heavy"], alpha=0.7, label="Larger in heavy users")
ctrl_p = mpatches.Patch(color=COLORS["control"], alpha=0.7, label="Larger in controls")
ax.legend(handles=[heavy_p, ctrl_p], fontsize=9)
ax.spines[["top", "right"]].set_visible(False)

fig.tight_layout()
fig.savefig(FIG_DIR / f"effect_sizes_ses-{SESSION}.png", dpi=150)
plt.close(fig)
print(f"[viz]   ✓ effect_sizes_ses-{SESSION}.png")

# ── 2. Group mean comparison bar chart ────────────────────────────────────────
print("[viz] Generating group means bar chart...")
plot_df = res_df.nlargest(12, lambda x: x["cohens_d"].abs())

fig, ax = plt.subplots(figsize=(14, 6))
x = np.arange(len(plot_df))
w = 0.35

ax.bar(x - w/2, plot_df["mean_heavy"], w,
       yerr=plot_df["std_heavy"],
       label="Heavy Users", color=COLORS["heavy"],
       alpha=0.7, capsize=4)
ax.bar(x + w/2, plot_df["mean_control"], w,
       yerr=plot_df["std_control"],
       label="Controls", color=COLORS["control"],
       alpha=0.7, capsize=4)

# Significance markers
if "sig_fdr05" in plot_df.columns:
    for i, (_, row) in enumerate(plot_df.iterrows()):
        if row.get("sig_fdr05", False):
            ymax = max(row["mean_heavy"] + row["std_heavy"],
                       row["mean_control"] + row["std_control"])
            ax.text(x[i], ymax * 1.03, "*", ha="center", fontsize=14, color="#333")

ax.set_xticks(x)
ax.set_xticklabels(
    plot_df["roi"].str.replace(r"(Left-|Right-|lh_|rh_)", "", regex=True).str[:15],
    fontsize=8, rotation=30, ha="right"
)
ax.set_ylabel("Volume (mm³) / Thickness (mm)", fontsize=11)
ax.set_title(
    f"Top ROIs by Effect Size — Heavy Users vs Controls (ses-{SESSION})\n"
    "(* = FDR q<0.05, error bars = 1 SD)",
    fontsize=12
)
ax.legend(fontsize=10)
ax.spines[["top", "right"]].set_visible(False)

fig.tight_layout()
fig.savefig(FIG_DIR / f"group_means_ses-{SESSION}.png", dpi=150)
plt.close(fig)
print(f"[viz]   ✓ group_means_ses-{SESSION}.png")

# ── 3. Summary table ───────────────────────────────────────────────────────────
summary = res_df[["roi", "mean_heavy", "mean_control", "cohens_d",
                   "p_uncorrected", "p_fdr" if "p_fdr" in res_df.columns else "p_uncorrected"]].copy()
summary.to_csv(FIG_DIR / f"summary_table_ses-{SESSION}.csv", index=False)
print(f"[viz]   ✓ summary_table_ses-{SESSION}.csv")

# ── Summary ───────────────────────────────────────────────────────────────────
print()
print("✅ Group comparison figures saved to: data/processed/figures/")
print()
print("Single-subject QC reports (generated by DeepPrep):")
print(f"   outputs/deepprep/QC/sub-*_ses-{SESSION}.html")
print()
print("Open these HTML files in a browser to inspect:")
print("  • Segmentation quality")
print("  • Surface reconstruction")
print("  • Spatial normalization")
print("  • Parcellation results")
